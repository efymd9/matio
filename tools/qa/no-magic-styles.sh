#!/usr/bin/env bash
# Механический запрет «магии» в фичах: цветовой литерал не имеет права
# появиться в пользовательских компонентах — только токены дизайн-системы
# (@theme в app/globals.css: gold, cream, espresso, burgundy, rust, …).
#
# ПОЧЕМУ ИМЕННО ЭТО: дизайн-система разрушается не одним махом, а по одному
# `bg-[#3a2a1e]` за PR. Через полгода «золотой» в проекте четырёх оттенков, и
# никто не помнит, какой правильный. Ревьюер такое пропускает — он смотрит на
# логику; grep не пропускает никогда.
#
# ЧТО ПРОВЕРЯЕТСЯ: произвольные значения Tailwind с цветовым литералом
# (`bg-[#…]`, `text-[rgb(…)]`, `border-[oklch(…)]` и т.п.) в публичных
# поверхностях. На 31.07.2026 таких — НОЛЬ, поэтому чек красный только на
# новом нарушении.
#
# ЧТО ПОКА НЕ ПРОВЕРЯЕТСЯ (осознанно): хардкоды в пропах (`color="#f6efe4"`,
# 17 штук), произвольные тени (`shadow-[0_18px_40px_-16px_rgba(…)]`, 32) и
# градиенты в inline-стилях (11). Это существующий долг: включить их сегодня
# значит получить красный CI на живом коде и приучить всех обходить чек.
# Долг заведён отдельной задачей — когда он закрыт, паттерны переезжают сюда.
#
# АДМИНКА (components/admin) НЕ сканируется: её SVG-графики строят палитры
# программно, и это внутренний инструмент, а не бренд.
set -uo pipefail

SCAN_DIRS=(
  "components/site"
  "components/watch"
  "app/(public)"
  "app/watch"
)

# Цветовой литерал внутри произвольного значения Tailwind: -[#hex,
# -[rgb(…, -[rgba(…, -[hsl(…, -[oklch(…
PATTERN='-\[(#[0-9a-fA-F]{3,8}|(rgb|rgba|hsl|hsla|oklch|oklab)\()'

# Файлы отбираются через find, а не через grep --include: у ugrep (частый
# локальный дублёр grep на macOS) --include другой семантики, и чек молча
# сканировал не то. Паттерн передаётся через -e — он начинается с дефиса и
# иначе уезжает в опции grep. Обе грабли пойманы при установке чека.
found=0
for dir in "${SCAN_DIRS[@]}"; do
  [ -d "$dir" ] || continue
  while IFS= read -r hit; do
    [ -n "$hit" ] || continue
    if [ "$found" -eq 0 ]; then
      echo "✗ Цветовые литералы в фичах — используйте токены дизайн-системы:"
      echo
    fi
    found=1
    echo "  $hit"
  done < <(
    find "$dir" -type f -name '*.tsx' ! -name '*.stories.tsx' -print0 \
      | xargs -0 grep -nHE -e "$PATTERN" 2>/dev/null
  )
done

if [ "$found" -eq 1 ]; then
  echo
  echo "Замените литерал на токен из app/globals.css (@theme): text-gold,"
  echo "bg-espresso-2, border-rust/30 и т.д. Нужного оттенка нет — он"
  echo "добавляется в @theme И в таблицу lab/tokens.stories.tsx тем же PR,"
  echo "чтобы система оставалась одним источником правды."
  exit 1
fi

echo "✓ Цветовых литералов в фичах нет"
